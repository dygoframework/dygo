// genFile is the file dygo gen writes in each package with directives.
const genFile = "dygo_gen.go"

const genHeader = "// Code generated by dygo gen. DO NOT EDIT."

// knownPackages resolves package names in //dygo:use expressions that the
// source file does not import (it could not: the import would be unused).
// Other packages need a //dygo:import line on the controller type.
var knownPackages = map[string]string{
	"dygo": frameworkPath, "openapi": frameworkPath + "/openapi", "meta": frameworkPath + "/meta",
	"validate": frameworkPath + "/validate", "interceptors": frameworkPath + "/interceptors",
	"ratelimit": frameworkPath + "/ratelimit", "errs": frameworkPath + "/errs",
	"http": "net/http", "time": "time",
}

var routeMethods = map[string]string{
	"get": "Get", "post": "Post", "put": "Put", "patch": "Patch", "delete": "Delete",
	"head": "Head", "options": "Options", "all": "All",
}

func cmdGen(args []string, stdout io.Writer) error {
	fs := newFlags("gen")
	check := fs.Bool("check", false, "fail if a generated file is missing or out of date, without writing")
	pos, _, err := parseFlags(fs, args)
	if err != nil {
		return err
	}
	if len(pos) == 0 {
		pos = []string{"."}
	}
	var stale []string
	for _, root := range pos {
		dirs, err := packageDirs(root)
		if err != nil {
			return err
		}
		for _, dir := range dirs {
			src, err := genPackage(dir)
			if err != nil {
				return err
			}
			changed, err := syncGenFile(filepath.Join(dir, genFile), src, *check)
			if err != nil {
				return err
			}
			if changed {
				stale = append(stale, filepath.Join(dir, genFile))
			}
		}
	}
	for _, f := range stale {
		switch {
		case *check:
			fmt.Fprintln(stdout, "STALE", f)
		default:
			fmt.Fprintln(stdout, "WRITE", f)
		}
	}
	if *check && len(stale) > 0 {
		fmt.Fprintln(stdout, "run dygo gen to update")
		return exitError(1)
	}
	return nil
}

// packageDirs lists root and every directory below it with Go files,
// skipping hidden directories, vendor and testdata.
func packageDirs(root string) ([]string, error) {
	var dirs []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		name := d.Name()
		if path != root && (strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") || name == "vendor" || name == "testdata") {
			return filepath.SkipDir
		}
		dirs = append(dirs, path)
		return nil
	})
	return dirs, err
}

// syncGenFile writes src to path, or removes path when src is nil and path
// holds generated code. It reports whether the file changed (or would).
func syncGenFile(path string, src []byte, checkOnly bool) (bool, error) {
	old, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return false, err
	}
	if src == nil {
		if old == nil || !bytes.HasPrefix(old, []byte(genHeader)) {
			return false, nil
		}
		if checkOnly {
			return true, nil
		}
		return true, os.Remove(path)
	}
	if bytes.Equal(old, src) {
		return false, nil
	}
	if old != nil && !bytes.HasPrefix(old, []byte(genHeader)) {
		return false, fmt.Errorf("%s exists and was not generated by dygo gen", path)
	}
	if checkOnly {
		return true, nil
	}
	return true, os.WriteFile(path, src, 0o644)
}

// controllerDef is a type marked //dygo:controller and its routes.
type controllerDef struct {
	typ    string
	prefix string
	uses   []string
	routes []routeDirective
}

type routeDirective struct {
	method  string // Router method: Get, Post, ...
	path    string
	handler string // Handle, HandleNoInput or HandleRaw
	fn      string // the method name
	recv    string // the receiver type
	uses    []string
	pos     token.Position
}

// genPackage parses the package in dir and returns its generated file, or
// nil when it has no directives.
func genPackage(dir string) ([]byte, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	var pkg string
	ctrls := map[string]*controllerDef{}
	var pending []routeDirective               // matched to their controller at the end
	handWritten := map[string]token.Position{} // types with a Routes method outside the generated file
	imports := map[string]string{}             // name -> path, for the expressions in //dygo:use
	declared := map[string]string{}            // from //dygo:import
	type use struct {
		expr      string
		pos       token.Position
		fileNames map[string]string
	}
	var uses []use // resolved at the end, when every //dygo:import is known
	var errs []error
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || name == genFile {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		pkg = f.Name.Name
		fileImports := map[string]string{}
		for _, imp := range f.Imports {
			p, _ := strconv.Unquote(imp.Path.Value)
			n := p[strings.LastIndex(p, "/")+1:]
			if imp.Name != nil {
				n = imp.Name.Name
			}
			fileImports[n] = p
		}
		useImports := func(exprs []string, pos token.Position) {
			for _, x := range exprs {
				uses = append(uses, use{x, pos, fileImports})
			}
		}
		for _, decl := range f.Decls {
			switch d := decl.(type) {
			case *ast.GenDecl:
				if d.Tok != token.TYPE {
					continue
				}
				for _, spec := range d.Specs {
					ts := spec.(*ast.TypeSpec)
					doc := ts.Doc
					if doc == nil && len(d.Specs) == 1 {
						doc = d.Doc
					}
					ds, err := directives(fset, doc)
					if err != nil {
						errs = append(errs, err)
						continue
					}
					var c *controllerDef
					for _, dv := range ds {
						switch dv.name {
						case "controller":
							c = &controllerDef{typ: ts.Name.Name, prefix: dv.arg}
							ctrls[c.typ] = c
						case "import":
							p, err := strconv.Unquote(dv.arg)
							if err != nil {
								p = dv.arg
							}
							declared[p[strings.LastIndex(p, "/")+1:]] = p
						case "use":
							if c == nil {
								errs = append(errs, fmt.Errorf("%s: //dygo:use on a type needs //dygo:controller first", dv.pos))
								continue
							}
							c.uses = append(c.uses, dv.arg)
							useImports([]string{dv.arg}, dv.pos)
						default:
							errs = append(errs, fmt.Errorf("%s: //dygo:%s is for methods; types take controller, use and import", dv.pos, dv.name))
						}
					}
				}
			case *ast.FuncDecl:
				if d.Recv == nil || len(d.Recv.List) != 1 {
					continue
				}
				recv := recvType(d.Recv.List[0].Type)
				if d.Name.Name == "Routes" {
					handWritten[recv] = fset.Position(d.Pos())
				}
				ds, err := directives(fset, d.Doc)
				if err != nil {
					errs = append(errs, err)
					continue
				}
				var routeUses []string
				var routes []routeDirective
				for _, dv := range ds {
					if dv.name == "use" {
						routeUses = append(routeUses, dv.arg)
						useImports([]string{dv.arg}, dv.pos)
						continue
					}
					m, ok := routeMethods[dv.name]
					if !ok {
						errs = append(errs, fmt.Errorf("%s: unknown directive //dygo:%s", dv.pos, dv.name))
						continue
					}
					h, err := handlerKind(d.Type, fileImports)
					if err != nil {
						errs = append(errs, fmt.Errorf("%s: %s: %w", dv.pos, d.Name.Name, err))
						continue
					}
					if dv.arg == "" {
						dv.arg = "/"
					}
					routes = append(routes, routeDirective{method: m, path: dv.arg, handler: h, fn: d.Name.Name, recv: recv, pos: dv.pos})
				}
				if len(routeUses) > 0 && len(routes) == 0 {
					errs = append(errs, fmt.Errorf("%s: //dygo:use on %s without a route directive", fset.Position(d.Pos()), d.Name.Name))
				}
				for _, r := range routes {
					r.uses = routeUses
					pending = append(pending, r)
				}
			}
		}
	}
	for _, u := range uses {
		for _, id := range exprPackages(u.expr) {
			p, ok := u.fileNames[id]
			if !ok {
				p, ok = declared[id]
			}
			if !ok {
				p, ok = knownPackages[id]
			}
			if !ok {
				errs = append(errs, fmt.Errorf("%s: //dygo:use %s: unknown package %s; add //dygo:import \"path/to/%s\" to the controller type", u.pos, u.expr, id, id))
				continue
			}
			imports[id] = p
		}
	}
	for _, r := range pending {
		c, ok := ctrls[r.recv]
		if !ok {
			errs = append(errs, fmt.Errorf("%s: %s has route directives, but type %s has no //dygo:controller", r.pos, r.fn, r.recv))
			continue
		}
		c.routes = append(c.routes, r)
	}
	for typ := range ctrls {
		if pos, ok := handWritten[typ]; ok {
			errs = append(errs, fmt.Errorf("%s: %s has //dygo: directives and a Routes method; remove one", pos, typ))
		}
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}
	if len(ctrls) == 0 {
		return nil, nil
	}
	return emitRoutes(pkg, ctrls, imports)
}

func emitRoutes(pkg string, ctrls map[string]*controllerDef, imports map[string]string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "%s\n\npackage %s\n\nimport (\n", genHeader, pkg)
	if _, ok := imports["dygo"]; !ok {
		imports["dygo"] = frameworkPath
	}
	if imports["dygo"] != frameworkPath {
		return nil, fmt.Errorf("package %s: the name dygo is imported as %s", pkg, imports["dygo"])
	}
	// Standard library first, then the rest, as goimports groups them.
	names := slices.Sorted(maps.Keys(imports))
	for _, std := range []bool{true, false} {
		for _, name := range names {
			p := imports[name]
			if !strings.Contains(firstElem(p), ".") != std {
				continue
			}
			if name == p[strings.LastIndex(p, "/")+1:] {
				fmt.Fprintf(&b, "\t%q\n", p)
			} else {
				fmt.Fprintf(&b, "\t%s %q\n", name, p)
			}
		}
		b.WriteString("\n")
	}
	b.WriteString(")\n")
	for _, typ := range slices.Sorted(maps.Keys(ctrls)) {
		c := ctrls[typ]
		fmt.Fprintf(&b, "\n// Routes registers the routes declared with //dygo: directives.\nfunc (c *%s) Routes(r dygo.Router) {\n", c.typ)
		if c.prefix != "" && c.prefix != "/" {
			fmt.Fprintf(&b, "\tr = r.Prefix(%q)\n", c.prefix)
		}
		if len(c.uses) > 0 {
			fmt.Fprintf(&b, "\tr = r.Use(%s)\n", strings.Join(c.uses, ", "))
		}
		for _, r := range c.routes {
			args := []string{strconv.Quote(r.path), fmt.Sprintf("dygo.%s(c.%s)", r.handler, r.fn)}
			fmt.Fprintf(&b, "\tr.%s(%s)\n", r.method, strings.Join(append(args, r.uses...), ", "))
		}
		b.WriteString("}\n")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("package %s: generated code does not parse (check the //dygo:use expressions): %w", pkg, err)
	}
	return src, nil
}

type directive struct {
	name, arg string
	pos       token.Position
}

// directives returns the //dygo:name arg lines of a doc comment.
func directives(fset *token.FileSet, doc *ast.CommentGroup) ([]directive, error) {
	if doc == nil {
		return nil, nil
	}
	var out []directive
	for _, c := range doc.List {
		text, ok := strings.CutPrefix(c.Text, "//dygo:")
		if !ok {
			continue
		}
		name, arg, _ := strings.Cut(text, " ")
		d := directive{name: name, arg: strings.TrimSpace(arg), pos: fset.Position(c.Pos())}
		if d.name == "use" {
			if d.arg == "" {
				return nil, fmt.Errorf("%s: //dygo:use needs a route option expression", d.pos)
			}
			if _, err := parser.ParseExpr(d.arg); err != nil {
				return nil, fmt.Errorf("%s: //dygo:use %s: %w", d.pos, d.arg, err)
			}
		} else if strings.ContainsAny(d.arg, " \t") {
			return nil, fmt.Errorf("%s: //dygo:%s takes one path; put route options in //dygo:use lines", d.pos, d.name)
		}
		out = append(out, d)
	}
	return out, nil
}

// exprPackages returns the identifiers used as package qualifiers in x.
func exprPackages(x string) []string {
	e, err := parser.ParseExpr(x)
	if err != nil {
		return nil
	}
	var ids []string
	ast.Inspect(e, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok && !slices.Contains(ids, id.Name) {
				ids = append(ids, id.Name)
			}
		}
		return true
	})
	return ids
}

func recvType(e ast.Expr) string {
	if s, ok := e.(*ast.StarExpr); ok {
		e = s.X
	}
	if ix, ok := e.(*ast.IndexExpr); ok {
		e = ix.X
	}
	if id, ok := e.(*ast.Ident); ok {
		return id.Name
	}
	return ""
}

// handlerKind picks the dygo wrapper from the method's parameters:
// (ctx) is HandleNoInput, (ctx, In) is Handle, (http.ResponseWriter,
// *http.Request) is HandleRaw. The compiler checks the rest.
func handlerKind(ft *ast.FuncType, imports map[string]string) (string, error) {
	var params []ast.Expr
	for _, f := range ft.Params.List {
		n := max(len(f.Names), 1)
		for range n {
			params = append(params, f.Type)
		}
	}
	isHTTP := func(e ast.Expr, name string) bool {
		sel, ok := e.(*ast.SelectorExpr)
		if !ok || sel.Sel.Name != name {
			return false
		}
		id, ok := sel.X.(*ast.Ident)
		return ok && imports[id.Name] == "net/http"
	}
	switch len(params) {
	case 1:
		return "HandleNoInput", nil
	case 2:
		if isHTTP(params[0], "ResponseWriter") {
			return "HandleRaw", nil
		}
		return "Handle", nil
	}
	return "", errors.New("a handler takes (ctx), (ctx, In) or (http.ResponseWriter, *http.Request)")
}
